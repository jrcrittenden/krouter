#!/usr/bin/env node
// Regenerates open-sse/config/veniceModels.js from Venice's public catalog.
//
//   node scripts/sync-venice-models.mjs
//
// GET /api/v1/models?type=<t> needs no API key. Venice ships new media models
// every few weeks (142 video ids on 2026-11-08), so the static list is generated
// instead of hand-kept. Text models are NOT listed here: chat ids pass through
// (passthroughModels) and the dashboard reads them live via LIVE_FETCH.venice.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const BASE = "https://api.venice.ai/api/v1/models";
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "open-sse", "config", "veniceModels.js");

async function list(type) {
  const res = await fetch(`${BASE}?type=${type}`, { headers: { "User-Agent": "krouter-sync/1.0" } });
  if (!res.ok) throw new Error(`GET ${type}: HTTP ${res.status}`);
  const json = await res.json();
  return (json.data || []).filter((m) => m?.id && m.model_spec?.offline !== true);
}

const name = (m) => m.model_spec?.name || m.id;
const deprecated = (m) => (m.model_spec?.deprecation?.date ? { deprecated: true } : {});
const compact = (o) => Object.fromEntries(Object.entries(o).filter(([, v]) => v !== undefined && v !== null && !(Array.isArray(v) && !v.length)));

const builders = {
  embedding: (m) => compact({ id: m.id, name: name(m), dimensions: m.model_spec?.embeddingDimensions, customDimensions: m.model_spec?.supportsCustomDimensions || undefined }),
  tts: (m) => compact({ id: m.id, name: name(m), voices: m.model_spec?.voices, defaultVoice: m.model_spec?.default_voice, defaultFormat: m.model_spec?.default_format }),
  asr: (m) => ({ id: m.id, name: name(m) }),
  image: (m) => {
    const c = m.model_spec?.constraints || {};
    return compact({
      id: m.id, name: name(m),
      // Models that publish aspectRatios take aspect_ratio (+ resolution); the rest take width/height.
      aspectRatios: c.aspectRatios, resolutions: c.resolutions,
      ...deprecated(m),
    });
  },
  inpaint: (m) => compact({ id: m.id, name: name(m), aspectRatios: m.model_spec?.constraints?.aspectRatios, maxInputImages: m.model_spec?.constraints?.maxInputImages }),
  upscale: (m) => ({ id: m.id, name: name(m) }),
  video: (m) => {
    const c = m.model_spec?.constraints || {};
    return compact({ id: m.id, name: name(m), modelType: c.model_type, durations: c.durations, resolutions: c.resolutions, aspectRatios: c.aspect_ratios, ...deprecated(m) });
  },
  music: (m) => {
    const s = m.model_spec || {};
    return compact({
      id: m.id, name: name(m),
      defaultDuration: s.default_duration, minDuration: s.min_duration, maxDuration: s.max_duration,
      lyricsRequired: s.lyrics_required || undefined, supportsLyrics: s.supports_lyrics || undefined,
      forceInstrumental: s.supports_force_instrumental || undefined,
      voices: s.voices, defaultVoice: s.default_voice, defaultFormat: s.default_format,
    });
  },
};

const EXPORTS = { embedding: "VENICE_EMBEDDING_MODELS", tts: "VENICE_TTS_MODELS", asr: "VENICE_STT_MODELS", image: "VENICE_IMAGE_MODELS", inpaint: "VENICE_EDIT_MODELS", upscale: "VENICE_UPSCALE_MODELS", video: "VENICE_VIDEO_MODELS", music: "VENICE_MUSIC_MODELS" };

// Guard against a degraded catalog response wiping the lists: refuse to write if a
// type comes back empty or shrinks by more than half versus the current file.
// Override with --force after checking Venice really retired the models.
const force = process.argv.includes("--force");
async function currentCounts() {
  try {
    const mod = await import(`${OUT}?t=${Date.now()}`);
    return Object.fromEntries(Object.entries(EXPORTS).map(([type, name]) => [type, mod[name]?.length ?? 0]));
  } catch {
    return {}; // no file yet (first run)
  }
}

const before = await currentCounts();
const sections = [];
const problems = [];
for (const [type, exportName] of Object.entries(EXPORTS)) {
  const rows = (await list(type)).map(builders[type]);
  const prev = before[type] ?? 0;
  if (rows.length === 0) problems.push(`${type}: catalog returned 0 models`);
  else if (prev > 0 && rows.length < prev / 2) problems.push(`${type}: ${prev} → ${rows.length} models`);
  sections.push(`export const ${exportName} = [\n${rows.map((r) => `  ${JSON.stringify(r)},`).join("\n")}\n];\n\n`);
  console.log(`${type.padEnd(10)} ${String(prev).padStart(4)} → ${rows.length}`);
}
if (problems.length && !force) {
  console.error(`refusing to write (rerun with --force if intended):\n  ${problems.join("\n  ")}`);
  process.exit(1);
}

// The date stamp is in the header, so an unchanged catalog would still produce a
// diff. Keep the old header when the model data is identical.
const body = sections.join("");
const header = `// GENERATED by scripts/sync-venice-models.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand;\n// rerun the script. Source: ${BASE}?type=<type> (public, no key). Offline models are skipped.\n\n`;
let previous = "";
try { previous = await readFile(OUT, "utf8"); } catch { /* first run */ }
const previousBody = previous.split("\n").slice(3).join("\n");
if (previousBody === body) {
  console.log("no catalog changes");
} else {
  await writeFile(OUT, header + body);
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
}
